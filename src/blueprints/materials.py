"""Realistic-mode material catalogue: load and validate.

The catalogue is ``inputs/materials/catalogue.yaml``; its contract is the
comment at the top of that file and docs/materials/README.md. Geometry does
not carry materials: the viewer resolves each mesh (``<label>__<id>__``)
through the selectors here, so later glTF fixtures can reuse the same ids.

    python -m blueprints.materials      # prints problems, exit 1 if any
"""

from __future__ import annotations

import json
import re
import struct
import sys
from pathlib import Path
from typing import Any

import yaml

REPO_ROOT = Path(__file__).resolve().parents[2]
CATALOGUE_PATH = REPO_ROOT / "inputs" / "materials" / "catalogue.yaml"
README_PATH = REPO_ROOT / "docs" / "materials" / "README.md"
TABLE_START = "<!-- materials-table:start (generated by python -m blueprints.materials --write-readme) -->"
TABLE_END = "<!-- materials-table:end -->"
MODELS_DIR = REPO_ROOT / "docs" / "models"
# Floor-plan models the catalogue covers. obyvak (the acoustic roof model) is
# out of scope: it keeps the existing realistic presets.
COVERED_MODELS = ("ground_floor", "bathroom_107", "bathroom_120")

REQUIRED = ("id", "name", "applies_to", "base_color", "roughness", "metalness", "tile_size_m", "status", "source", "notes")
OPTIONAL = ("transmission", "opacity", "ior", "maps", "rotation_deg")
MAP_KEYS = ("color", "normal", "roughness", "ao")
STATUSES = ("known", "assumed")
ID_RE = re.compile(r"^[a-z0-9]+(?:-[a-z0-9]+)*$")
HEX_RE = re.compile(r"^#[0-9a-fA-F]{6}$")
MAX_TEXTURE_PX = 2048


def load_catalogue(path: Path = CATALOGUE_PATH) -> list[dict[str, Any]]:
    data = yaml.safe_load(path.read_text(encoding="utf-8"))
    if not isinstance(data, list):
        raise ValueError(f"{path}: top level must be a list of materials")
    return data


def _jpeg_size(path: Path) -> tuple[int, int] | None:
    data = path.read_bytes()
    if data[:2] != b"\xff\xd8":
        return None
    i = 2
    while i + 9 < len(data):
        if data[i] != 0xFF:
            i += 1
            continue
        marker = data[i + 1]
        if marker in (0xC0, 0xC1, 0xC2):
            h, w = struct.unpack(">HH", data[i + 5 : i + 9])
            return w, h
        seg = struct.unpack(">H", data[i + 2 : i + 4])[0]
        i += 2 + seg
    return None


def _num(v: Any) -> bool:
    return isinstance(v, (int, float)) and not isinstance(v, bool)


def glb_node_names(model: str) -> list[str] | None:
    """Node names from docs/models/<model>.glb, or None if it is an LFS pointer."""
    path = MODELS_DIR / f"{model}.glb"
    if not path.exists():
        return None
    with path.open("rb") as f:
        head = f.read(20)
        if head[:4] != b"glTF":
            return None
        length = struct.unpack("<I", head[12:16])[0]
        doc = json.loads(f.read(length))
    return [n.get("name", "") for n in doc.get("nodes", [])]


def model_labels() -> set[str]:
    """Every part label the covered models emit (from the committed parts.json)."""
    labels: set[str] = set()
    for model in COVERED_MODELS:
        path = MODELS_DIR / f"{model}.parts.json"
        if path.exists():
            for group in json.loads(path.read_text(encoding="utf-8")):
                labels.update(group.get("children", []))
        names = glb_node_names(model) or []
        for name in names:
            if "__" in name:
                labels.add(name.split("__")[0])
    return labels


def resolve(catalogue: list[dict[str, Any]], label: str, mesh_id: str | None) -> list[str]:
    """Material ids that win for one mesh (more than one means ambiguous)."""
    best: list[tuple[int, str]] = []
    for mat in catalogue:
        for sel in (mat.get("applies_to") or {}).get("selectors") or []:
            if sel.get("label") != label:
                continue
            if "ids" in sel:
                rank = 3 if mesh_id in sel["ids"] else -1
            elif "id_pattern" in sel:
                rank = 2 if mesh_id and re.search(sel["id_pattern"], mesh_id) else -1
            else:
                rank = 1
            if rank > 0:
                best.append((rank, mat["id"]))
    if not best:
        return []
    top = max(r for r, _ in best)
    return sorted({m for r, m in best if r == top})


def validate(catalogue: list[dict[str, Any]] | None = None) -> list[str]:
    cat = load_catalogue() if catalogue is None else catalogue
    errors: list[str] = []
    seen: set[str] = set()
    for i, mat in enumerate(cat):
        where = f"entry {i} ({mat.get('id', '?')})"
        if not isinstance(mat, dict):
            errors.append(f"{where}: not a mapping")
            continue
        for key in REQUIRED:
            if key not in mat:
                errors.append(f"{where}: missing {key}")
        for key in mat:
            if key not in REQUIRED and key not in OPTIONAL:
                errors.append(f"{where}: unknown field {key}")
        mid = mat.get("id", "")
        if not isinstance(mid, str) or not ID_RE.match(mid):
            errors.append(f"{where}: id must be kebab-case")
        if mid in seen:
            errors.append(f"{where}: duplicate id")
        seen.add(mid)
        if not isinstance(mat.get("base_color"), str) or not HEX_RE.match(mat["base_color"]):
            errors.append(f"{where}: base_color must be #rrggbb")
        for key in ("roughness", "metalness", "transmission", "opacity"):
            if key in mat and not (_num(mat[key]) and 0 <= mat[key] <= 1):
                errors.append(f"{where}: {key} must be a number in 0..1")
        if "ior" in mat and not (_num(mat["ior"]) and 1 <= mat["ior"] <= 3):
            errors.append(f"{where}: ior must be in 1..3")
        if "rotation_deg" in mat and not _num(mat["rotation_deg"]):
            errors.append(f"{where}: rotation_deg must be a number")
        ts = mat.get("tile_size_m")
        if not (isinstance(ts, list) and len(ts) == 2 and all(_num(v) and v > 0 for v in ts)):
            errors.append(f"{where}: tile_size_m must be [w, h] > 0")
        if mat.get("status") not in STATUSES:
            errors.append(f"{where}: status must be one of {STATUSES}")
        if not isinstance(mat.get("source"), list) or not all(
            isinstance(u, str) and u.startswith("https://") for u in mat.get("source") or []
        ):
            errors.append(f"{where}: source must be a list of https URLs")
        if mat.get("status") == "known" and not mat.get("source"):
            errors.append(f"{where}: a known material needs a source")
        if not isinstance(mat.get("notes"), str) or len(mat.get("notes", "")) < 20:
            errors.append(f"{where}: notes must say what was matched or assumed")
        at = mat.get("applies_to")
        if not isinstance(at, dict) or not isinstance(at.get("description"), str):
            errors.append(f"{where}: applies_to needs a description")
        else:
            sels = at.get("selectors")
            if not isinstance(sels, list):
                errors.append(f"{where}: applies_to.selectors must be a list")
            else:
                for sel in sels:
                    if not isinstance(sel, dict) or not isinstance(sel.get("label"), str):
                        errors.append(f"{where}: selector needs a label: {sel!r}")
                        continue
                    extra = set(sel) - {"label", "ids", "id_pattern"}
                    if extra or ("ids" in sel and "id_pattern" in sel):
                        errors.append(f"{where}: bad selector {sel!r}")
                    if "id_pattern" in sel:
                        try:
                            re.compile(sel["id_pattern"])
                        except re.error as exc:
                            errors.append(f"{where}: bad id_pattern {sel['id_pattern']!r}: {exc}")
            if not sels and not at.get("pending"):
                errors.append(f"{where}: no selectors, so applies_to.pending must say what it is for")
        maps = mat.get("maps") or {}
        if not isinstance(maps, dict):
            errors.append(f"{where}: maps must be a mapping")
            maps = {}
        for key, rel in maps.items():
            if key not in MAP_KEYS:
                errors.append(f"{where}: unknown map {key}")
                continue
            path = REPO_ROOT / str(rel)
            if not str(rel).startswith("docs/materials/"):
                errors.append(f"{where}: map {key} must live under docs/materials/ (published)")
            if not path.is_file():
                errors.append(f"{where}: map {key} missing: {rel}")
                continue
            if not (path.parent / "LICENSE.txt").is_file():
                errors.append(f"{where}: {path.parent.name}/ has no LICENSE.txt")
            size = _jpeg_size(path) if path.suffix.lower() in (".jpg", ".jpeg") else None
            if size and max(size) > MAX_TEXTURE_PX:
                errors.append(f"{where}: {rel} is {size}, over {MAX_TEXTURE_PX}px")
    if errors:
        return errors

    # Coverage: every label resolves to exactly one material, and so does
    # every mesh in the committed GLBs.
    for label in sorted(model_labels()):
        if len(resolve(cat, label, None)) != 1:
            errors.append(f"label {label!r}: needs exactly one label-only selector, got {resolve(cat, label, None)}")
    for model in COVERED_MODELS:
        for name in glb_node_names(model) or []:
            parts = name.split("__")
            if len(parts) < 2 or not parts[1]:
                continue
            hits = resolve(cat, parts[0], parts[1])
            if len(hits) != 1:
                errors.append(f"{model} mesh {name!r}: resolves to {hits or 'nothing'}")
    return errors


def _selectors_text(mat: dict[str, Any]) -> str:
    out = []
    for sel in mat["applies_to"].get("selectors") or []:
        if "ids" in sel:
            out.append(f"`{sel['label']}` {', '.join(sel['ids'])}")
        elif "id_pattern" in sel:
            out.append(f"`{sel['label']}` /{sel['id_pattern']}/")
        else:
            out.append(f"`{sel['label']}`")
    if mat["applies_to"].get("pending"):
        out.append("pending")
    return ("; ".join(out) or "pending").replace("|", "\\|")


def readme_table(catalogue: list[dict[str, Any]] | None = None) -> str:
    cat = load_catalogue() if catalogue is None else catalogue
    lines = [TABLE_START]
    for status, title in (("known", "Known products"), ("assumed", "Assumed")):
        lines += ["", f"### {title}", "", "| Material | Colour | Rough / metal | Textures | Viewer selectors | Sources |", "| --- | --- | --- | --- | --- | --- |"]
        for m in cat:
            if m["status"] != status:
                continue
            maps = ", ".join(sorted((m.get("maps") or {}).keys())) or "none"
            src = " ".join(f"[{i + 1}]({u})" for i, u in enumerate(m.get("source") or [])) or "none"
            name = m["name"].replace("|", "/")
            lines.append(
                f"| **{name}** `{m['id']}` | `{m['base_color']}` | {m['roughness']} / {m['metalness']} "
                f"| {maps} | {_selectors_text(m)} | {src} |"
            )
    lines += ["", TABLE_END]
    return "\n".join(lines)


def readme_in_sync() -> bool:
    text = README_PATH.read_text(encoding="utf-8") if README_PATH.exists() else ""
    return readme_table() in text


def write_readme() -> None:
    text = README_PATH.read_text(encoding="utf-8")
    a, b = text.index(TABLE_START), text.index(TABLE_END) + len(TABLE_END)
    README_PATH.write_text(text[:a] + readme_table() + text[b:], encoding="utf-8")


def main() -> int:
    if "--write-readme" in sys.argv[1:]:
        write_readme()
    errors = validate()
    if not errors and not readme_in_sync():
        errors.append("docs/materials/README.md table is stale: python -m blueprints.materials --write-readme")
    for e in errors:
        print(e)
    if not errors:
        print(f"{len(load_catalogue())} materials OK")
    return 1 if errors else 0


if __name__ == "__main__":
    sys.exit(main())
